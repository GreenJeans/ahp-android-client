internal fun sessionSnapshot(uri: String, fromSeq: Long, title: String = "Session C", status: Int = 8, inputNeeded: String? = null) =
    """{"resource":"$uri","fromSeq":$fromSeq,"state":{"provider":"copilotcli","title":"$title","status":$status,"lifecycle":"ready","activeClients":[],"chats":[]${inputNeeded?.let { ""","inputNeeded":$it""" }.orEmpty()}}}"""

internal fun actionFrame(channel: String, actionJson: String, seq: Long) =
    """{"jsonrpc":"2.0","method":"action","params":{"channel":"$channel","action":$actionJson,"serverSeq":$seq}}"""

internal fun titleChanged(title: String) = """{"type":"session/titleChanged","title":"$title"}"""

internal fun notification(method: String, paramsJson: String) = """{"jsonrpc":"2.0","method":"$method","params":$paramsJson}"""

/** One scripted connection: what a host answers, or why connecting fails. */
internal class HostScript(
    val listJson: String = fixture("live/list-sessions.json"),
    val failure: Throwable? = null,
    val missingSessions: Set<String> = emptySet(),
    /** What a subscribed session reports as waiting on the user, as the JSON array of `inputNeeded`; null for none. */
    val inputNeeded: String? = null,
    val onReconnect: (id: Long?) -> String = { id -> result(id, """{"type":"replay","actions":[],"missing":[]}""") },
    /** The `turnsNextCursor` a subscribed chat reports; null for a chat with nothing older. */
    val chatCursor: String? = null,
) {
    fun reply(method: String, id: Long?, params: JsonObject): String? = when (method) {
        "initialize" -> initializeReply(id, params)
        "listSessions" -> result(id, listJson)
        "subscribe" -> subscribeReply(id, params["channel"]!!.jsonPrimitive.content)
        "fetchTurns" -> result(id, "{}")
        "reconnect" -> onReconnect(id)
        else -> null
    }

    private fun initializeReply(id: Long?, params: JsonObject): String {
        val base = Json.parseToJsonElement(fixture("live/initialize-result.json")).jsonObject
        val sessionSnapshots = params["initialSubscriptions"]!!.jsonArray
            .map { it.jsonPrimitive.content }
            .filter { it.startsWith("ahp-session:/") }
            .map { Json.parseToJsonElement(sessionSnapshot(it, INITIAL_SEQ)) }
        val merged = JsonObject(base + ("snapshots" to JsonArray(base["snapshots"]!!.jsonArray + sessionSnapshots)))
        return result(id, merged.toString())
    }

    private fun subscribeReply(id: Long?, channel: String): String = when {
        channel.startsWith("ahp-chat:/") ->
            if (channel in missingSessions) error(id, -32008, "no such chat") else result(id, """{"snapshot":${chatSnapshotJson(channel, SNAPSHOT_SEQ, cursor = chatCursor)}}""")
        channel in missingSessions -> error(id, -32001, "no such session")
        else -> result(id, """{"snapshot":${sessionSnapshot(channel, SNAPSHOT_SEQ, inputNeeded = inputNeeded)}}""")
    }
}

/** Hands out one fake host connection per attempt, in order, and records how each was opened. */
internal class ScriptedConnector(vararg scripts: HostScript) : dev.ahpclient.state.HostConnector {
    private val queue = ArrayDeque(scripts.toList())
    val connects = mutableListOf<Pair<String, Long>>()
    val sockets = mutableListOf<FakeSocket>()

    override suspend fun connect(clientId: String, initialServerSeq: Long, scope: CoroutineScope): AhpConnection {
        connects += clientId to initialServerSeq
        val script = queue.removeFirstOrNull() ?: throw IOException("no more scripted connections")
        script.failure?.let { throw it }
        val socket = FakeSocket(script::reply)
        sockets += socket
        return AhpConnection(socket, scope, CapabilityPolicy.READ, clientId, initialServerSeq, requestTimeoutMs = 5_000)
    }
}
